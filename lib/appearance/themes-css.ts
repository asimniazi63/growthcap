// Turns the palettes into the text of app/themes.css. scripts/build-themes.ts writes it, and a test checks the committed file
// still matches. The selectors match any element, not only <html>, so a settings preview can show a scheme without switching the page.
import { COLOR_TOKENS, PALETTES, SHADOW_TOKENS } from "./palettes";
import { SCHEME_IDS, type Mode } from "./schemes";

const MODES: Mode[] = ["light", "dark"];

export function renderThemesCss(): string {
  const out = ["/* Generated by scripts/build-themes.ts from lib/appearance/palettes.ts. Do not edit by hand. */", ""];
  for (const scheme of SCHEME_IDS) {
    for (const mode of MODES) {
      const tokens = PALETTES[scheme][mode];
      out.push(`[data-scheme="${scheme}"][data-mode="${mode}"] {`, `  color-scheme: ${mode};`);
      for (const name of COLOR_TOKENS) out.push(`  --color-${name}: ${tokens[name]};`);
      for (const name of SHADOW_TOKENS) out.push(`  --${name}: ${tokens[name]};`);
      out.push("}", "");
    }
  }
  return out.join("\n");
}
