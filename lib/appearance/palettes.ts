// The colour values for every scheme, in light and dark. This file is the one source: scripts/build-themes.ts turns it into
// app/themes.css (npm run themes:build), and a test fails if the two drift apart. A value is a hex colour, or a CSS expression
// built from other tokens when the colour should follow them (for example the side rail, which is a tint of the page in most schemes).
import type { Mode, SchemeId } from "./schemes";

// The tokens every scheme must define. Each becomes a CSS variable --color-<name> and a Tailwind utility (bg-rail, text-on-rail).
export const COLOR_TOKENS = [
  "ink", "ink-2", "ink-3", "paper", "paper-2", "surface", "line", "line-strong",
  "brand", "brand-strong", "brand-tint", "ahead", "ahead-tint", "behind", "behind-tint", "warn", "warn-tint", "estimate",
  "inverse", "on-inverse", "on-brand",
  // The plan line in charts, the logo square and its glyph, and the side rail with its text, muted text, faint text and active item.
  "plan", "mark", "on-mark", "rail", "on-rail", "on-rail-2", "on-rail-3", "rail-active",
] as const;
export type ColorToken = (typeof COLOR_TOKENS)[number];

// Shadows are not colours, so they get their own variables (--shadow-card, --shadow-pop).
export const SHADOW_TOKENS = ["shadow-card", "shadow-pop"] as const;
export type ShadowToken = (typeof SHADOW_TOKENS)[number];

export type Tokens = Record<ColorToken | ShadowToken, string>;

